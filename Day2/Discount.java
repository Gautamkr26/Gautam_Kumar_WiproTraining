package Day2;

public class Discount {

	public static void main(String[] args) {

		  int amount = 6000;

	        if (amount > 5000) {
	            System.out.println("Discount: 20%");
	        } else if (amount > 2000) {
	            System.out.println("Discount: 10%");
	        } else {
	            System.out.println("No Discount");
	        }
	        
	}
	
}
